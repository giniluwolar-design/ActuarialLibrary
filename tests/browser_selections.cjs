// Synthetic user workflow at the actual browser/API/download seams.
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.argv[2] || 'http://127.0.0.1:8765');
    await page.locator('#method-table tbody tr').first().waitFor({ state: 'attached' });
    await page.locator('[data-tab="methods"]').first().click();
    await page.locator('#reserve-selection').waitFor({ timeout: 5000 });
    const key = await page.evaluate(() => localStorage.getItem('actuarial-workspace'));
    const root = new URL(`/api/workspaces/${key}`, page.url()).toString();
    const original = await (await page.request.get(root)).json();
    const origin = await page.locator('#origin').inputValue();
    await page.locator('#selection-method').selectOption('paid_cl');
    await page.locator('#selection-note').fill('Reviewed saved paid development for this accident period.');
    await page.locator('#selection-confirm').check();
    await page.getByRole('button', { name: 'Save my selection', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#selection-status').textContent.includes('Revision 1'));
    const selected = await (await page.request.get(root)).json();
    assert.deepEqual(selected.analysis, original.analysis);
    assert.deepEqual(selected.scenarios, original.scenarios);
    assert.equal(selected.selection.revision, 1);
    assert.equal(selected.selection.analysis.results.filter(row => row.selected).length, 1);
    assert.equal(selected.selection.analysis.results.find(row => row.selected).origin, origin);
    assert((await page.locator('#selection-status').innerText()).includes('Partial'));
    const downloaded = page.waitForEvent('download');
    await page.locator('#selection-export').click();
    const stream = await (await downloaded).createReadStream();
    const chunks = [];
    for await (const chunk of stream) chunks.push(chunk);
    const unpacked = spawnSync('.venv/bin/python', ['-c', 'import io,json,sys,zipfile; z=zipfile.ZipFile(io.BytesIO(sys.stdin.buffer.read())); print(z.read("analysis.json").decode())'], { input: Buffer.concat(chunks), encoding: 'utf8' });
    assert.equal(unpacked.status, 0, unpacked.stderr);
    const exported = JSON.parse(unpacked.stdout);
    assert.deepEqual(exported.results, selected.selection.analysis.results);
    assert.equal(exported.metadata.selection_revision, 1);
    assert.equal(exported.metadata.selection_action_id, selected.selection.action_id);
    const stale = await browser.newPage();
    await stale.addInitScript(id => localStorage.setItem('actuarial-workspace', id), key);
    await stale.goto(process.argv[2] || 'http://127.0.0.1:8765');
    await stale.locator('#method-table tbody tr').first().waitFor({ state: 'attached' });
    await stale.locator('[data-tab="methods"]').first().click();
    await page.reload();
    await page.locator('#method-table tbody tr').first().waitFor({ state: 'attached' });
    await page.locator('[data-tab="methods"]').first().click();
    assert.equal(await page.locator('#selection-method').inputValue(), 'paid_cl');
    assert(!(await page.locator('#selection-confirm').isChecked()));
    await page.locator('#selection-method').selectOption('manual');
    await page.locator('#selection-manual').fill('-10');
    await page.locator('#selection-note').fill('Explicit signed stress case, not a final reserve approval.');
    await page.locator('#selection-confirm').check();
    await page.getByRole('button', { name: 'Save my selection', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#selection-status').textContent.includes('Revision 2'));
    const manual = await (await page.request.get(root)).json();
    assert.equal(manual.selection.analysis.results.find(row => row.selected).ultimate, -10);
    assert.deepEqual(manual.analysis, original.analysis);
    assert((await page.locator('#selection-warnings').innerText()).includes('negative outstanding'));
    await stale.locator('#selection-method').selectOption('incurred_cl');
    await stale.locator('#selection-note').fill('This stale choice must not replace a newer revision.');
    await stale.locator('#selection-confirm').check();
    await stale.getByRole('button', { name: 'Save my selection', exact: true }).click();
    await stale.waitForFunction(() => document.querySelector('#notice').textContent.includes('Workspace refreshed after a conflict'));
    assert.equal(await stale.locator('#selection-method').inputValue(), 'manual');
    assert(!(await stale.locator('#selection-confirm').isChecked()));
    const afterConflict = await (await page.request.get(root)).json();
    assert.deepEqual(afterConflict.selection, manual.selection);
    await stale.close();
    await page.locator('#reserve-selection').scrollIntoViewIfNeeded();
    await page.screenshot({ path: '/tmp/actuarial-selections-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: '/tmp/actuarial-selections-mobile.png' });
    await page.locator('#selection-method').selectOption('clear');
    await page.locator('#selection-note').fill('Withdraw the exploratory signed selection.');
    await page.locator('#selection-confirm').check();
    await page.getByRole('button', { name: 'Save my selection', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#selection-status').textContent.includes('Revision 3'));
    const cleared = await (await page.request.get(root)).json();
    assert(await page.locator('#selection-warnings').isHidden());
    assert.equal(cleared.selection.analysis.results.filter(row => row.selected).length, 0);
    assert.equal(cleared.selection_history.length, 3);
    assert.deepEqual(cleared.selection_history[0], selected.selection);
    assert.deepEqual(errors, []);
    console.log('PASS: explicit method/manual/clear actions, partial status, preserved baseline/history, refresh, stale-tab conflict, actual revision-pinned ZIP, mobile width; no page errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
